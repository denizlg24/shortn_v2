import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import openapiTS, { astToString } from "openapi-typescript";
import { createRestApi } from "../src/rest";

// Route registration must stay independent of runtime services and credentials.
const unavailable = (): never => {
  throw new Error("OpenAPI generation attempted to access infrastructure");
};
export async function generatedContracts() {
  const app = createRestApi({
    get db() {
      return unavailable();
    },
    get cache() {
      return unavailable();
    },
    get durable() {
      return unavailable();
    },
    pepper: "",
    linkDomain: "shortn.at",
    rolloutPercent: 0,
    clientIp: () => undefined,
    log: unavailable,
  });
  const response = await app.request("/openapi.json");
  if (!response.ok) throw new Error("Could not generate OpenAPI document");
  const spec = await response.text();
  // openapi-typescript validates and bundles through Redocly before emitting.
  const types = astToString(await openapiTS(spec));
  const files = new Map([
    [
      new URL("../openapi.json", import.meta.url),
      JSON.stringify(JSON.parse(spec), null, 2) + "\n",
    ],
    [
      new URL("../client/schema.d.ts", import.meta.url),
      "// Generated by bun run --cwd apps/api gen:contracts. Do not edit.\n" +
        types,
    ],
  ]);
  for (const [path, source] of files) {
    files.set(
      path,
      await format(source, {
        ...(await resolveConfig(fileURLToPath(path))),
        filepath: fileURLToPath(path),
      }),
    );
  }
  return files;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let drift = false;
  for (const [path, content] of await generatedContracts()) {
    if (check) {
      const existing = Bun.file(path);
      if (!(await existing.exists()) || (await existing.text()) !== content) {
        console.error(`Generated contract differs: ${path.pathname}`);
        drift = true;
      }
    } else {
      await mkdir(new URL(".", path), { recursive: true });
      await Bun.write(path, content);
    }
  }
  if (drift) process.exitCode = 1;
}
